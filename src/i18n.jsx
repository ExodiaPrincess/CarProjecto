export function panelName(lang, id, { rear = "tailgate", doors = 4 } = {}) {
  const P = PANELS[lang];
  if (id === "boot") return P.boot[rear] || P.boot.tailgate;
  if (doors === 2 && id === "doorFL") return P.doorL2;
  if (doors === 2 && id === "doorFR") return P.doorR2;
  return P[id] || id;
}

